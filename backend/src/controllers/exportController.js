import { query } from '../config/db.js';
import { generateBibTeX, generateAPA } from '../services/citationService.js';

async function verifyProjectOwnership(projectId, userId) {
  const result = await query(
    'SELECT * FROM projects WHERE id = $1 AND user_id = $2',
    [projectId, userId]
  );
  return result.rows.length > 0 ? result.rows[0] : null;
}

/**
 * Export research project as Markdown, JSON, or BibTeX.
 */
export async function exportProject(req, res) {
  try {
    const { id: projectId } = req.params;
    const { format, include_sources = true, include_synthesis = true } = req.validatedBody;

    const project = await verifyProjectOwnership(projectId, req.user.id);
    if (!project) {
      return res.status(404).json({ error: 'Project not found.' });
    }

    let sources = [];
    if (include_sources || format === 'bibtex') {
      const sourcesResult = await query(
        `SELECT id, title, authors, publication_year, source_type, url, file_name, created_at
         FROM sources WHERE project_id = $1 ORDER BY created_at ASC`,
        [projectId]
      );
      sources = sourcesResult.rows;
    }

    let synthesisReports = [];
    if (include_synthesis) {
      const synResult = await query(
        `SELECT id, title, source_ids, result, created_at
         FROM synthesis_reports WHERE project_id = $1 ORDER BY created_at DESC`,
        [projectId]
      );
      synthesisReports = synResult.rows;
    }

    const cleanTitle = project.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');

    if (format === 'json') {
      const exportData = {
        project: {
          id: project.id,
          title: project.title,
          description: project.description,
          domain: project.domain,
          created_at: project.created_at,
          exported_at: new Date().toISOString(),
        },
        sources: include_sources ? sources : undefined,
        synthesis_reports: include_synthesis ? synthesisReports : undefined,
      };

      return res.status(200).json({
        format: 'json',
        filename: `${cleanTitle}-report.json`,
        content: JSON.stringify(exportData, null, 2),
        data: exportData,
      });
    }

    if (format === 'bibtex') {
      if (sources.length === 0) {
        return res.status(200).json({
          format: 'bibtex',
          filename: `${cleanTitle}-bibliography.bib`,
          content: '% No sources found for this project.',
        });
      }

      const bibtexEntries = sources.map((s) => generateBibTeX(s)).join('\n\n');
      return res.status(200).json({
        format: 'bibtex',
        filename: `${cleanTitle}-bibliography.bib`,
        content: bibtexEntries,
      });
    }

    // Default: Markdown format
    let md = `# ${project.title}\n\n`;
    md += `**Domain**: ${project.domain}  \n`;
    md += `**Generated By**: ResearchHub AI  \n`;
    md += `**Date**: ${new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })}  \n\n`;

    if (project.description) {
      md += `## Abstract & Scope\n\n${project.description}\n\n`;
    }

    if (include_sources && sources.length > 0) {
      md += `## Ingested Research Sources\n\n`;
      sources.forEach((s, idx) => {
        md += `${idx + 1}. **${s.title}**  \n`;
        md += `   - Citation (APA): *${generateAPA(s)}*  \n`;
        md += `   - Type: \`${s.source_type.toUpperCase()}\`${s.authors ? ` | Authors: ${s.authors}` : ''}${s.publication_year ? ` | Year: ${s.publication_year}` : ''}\n\n`;
      });
    }

    if (include_synthesis && synthesisReports.length > 0) {
      md += `## Literature Synthesis & Comparative Analysis\n\n`;

      synthesisReports.forEach((sr, idx) => {
        md += `### Synthesis #${idx + 1}: ${sr.title}\n\n`;

        const resObj = typeof sr.result === 'string' ? JSON.parse(sr.result) : sr.result;

        if (resObj.theme) {
          md += `**Overarching Theme**: ${resObj.theme}\n\n`;
        }

        if (resObj.summary) {
          md += `#### Executive Summary\n\n${resObj.summary}\n\n`;
        }

        if (Array.isArray(resObj.comparison_matrix) && resObj.comparison_matrix.length > 0) {
          md += `#### Comparative Literature Matrix\n\n`;
          md += `| Source | Objective | Methodology | Key Findings | Limitations |\n`;
          md += `| :--- | :--- | :--- | :--- | :--- |\n`;

          resObj.comparison_matrix.forEach((row) => {
            const clean = (val) => (val || 'N/A').replace(/\|/g, '\\|').replace(/\n/g, ' ');
            md += `| **${clean(row.source_title)}** | ${clean(row.research_objective)} | ${clean(row.methodology)} | ${clean(row.key_findings)} | ${clean(row.limitations)} |\n`;
          });
          md += `\n`;
        }

        if (Array.isArray(resObj.research_gaps) && resObj.research_gaps.length > 0) {
          md += `#### Critical Research Gaps\n\n`;
          resObj.research_gaps.forEach((gap) => {
            md += `- ${gap}\n`;
          });
          md += `\n`;
        }

        if (Array.isArray(resObj.future_directions) && resObj.future_directions.length > 0) {
          md += `#### Recommended Future Directions\n\n`;
          resObj.future_directions.forEach((dir) => {
            md += `- ${dir}\n`;
          });
          md += `\n`;
        }
      });
    }

    md += `---\n*Generated by ResearchHub AI — Accelerating Academic & Professional Discovery.*`;

    return res.status(200).json({
      format: 'markdown',
      filename: `${cleanTitle}-report.md`,
      content: md,
    });
  } catch (err) {
    console.error('exportProject error:', err);
    return res.status(500).json({ error: 'Internal server error exporting project.' });
  }
}

